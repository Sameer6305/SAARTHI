"""
Planner-Executor Integration
=============================

Integrates the conversation layer with the existing planner-executor architecture.

ARCHITECTURE:
```
┌─────────────────────────────────────────────────────────────────────┐
│                         USER INTERFACE                              │
│                    (Voice / Tray / Dialog)                          │
└────────────────────────────┬────────────────────────────────────────┘
                             │
                             ▼
┌─────────────────────────────────────────────────────────────────────┐
│                    DIALOGUE FLOW CONTROLLER                         │
│  ┌─────────────────────────────────────────────────────────────┐   │
│  │              ConversationManager                             │   │
│  │  • Intent Classification                                     │   │
│  │  • Entity Extraction                                         │   │
│  │  • State Management                                          │   │
│  │  • Confirmation Handling                                     │   │
│  └─────────────────────────────────────────────────────────────┘   │
└────────────────────────────┬────────────────────────────────────────┘
                             │
          ┌──────────────────┴──────────────────┐
          │                                     │
          ▼                                     ▼
┌────────────────────┐               ┌────────────────────┐
│      PLANNER       │               │     EXECUTOR       │
│  (Local LLM)       │               │  (Action Runner)   │
│                    │               │                    │
│  • Task breakdown  │──────────────▶│  • open_url        │
│  • Action planning │  ActionPlan   │  • search_web      │
│  • Context-aware   │               │  • read_file       │
│                    │               │  • calculate       │
└────────────────────┘               └────────────────────┘
          │                                     │
          ▼                                     ▼
┌────────────────────┐               ┌────────────────────┐
│   LOCAL LLM        │               │   PERMISSION       │
│   (Ollama)         │               │   GUARD            │
│                    │               │                    │
│  • Phi-3-mini      │               │  • Action whitelist│
│  • Mistral-7B      │               │  • Risk assessment │
│  • No cloud        │               │  • Audit logging   │
└────────────────────┘               └────────────────────┘
```

INTEGRATION POINTS:
1. DialogueFlowController receives user input
2. ConversationManager classifies intent and extracts entities
3. If action needed: Planner creates action plan
4. If confirmed: Executor runs the action
5. Response flows back through DialogueFlowController
"""

