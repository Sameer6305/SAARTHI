class Executor:
    """
    Executes approved action plans.
    
    SAFETY GUARANTEES:
    1. Only executes APPROVED actions
    2. All actions are audited
    3. Only whitelisted actions allowed
    4. No network actions without confirmation
    
    PERMISSION MODEL:
    - open_url: Allowed (opens in user's browser)
    - search_web: Allowed (opens search in browser)
    - read_file: Allowed for user-owned files
    - calculate: Always allowed (local computation)
    - explain: Always allowed (local LLM)
    - file_write: NEVER allowed
    - system_command: NEVER allowed
    """
    
    # Whitelisted action handlers
    ALLOWED_ACTIONS = {
        ActionType.OPEN_URL,
        ActionType.SEARCH_WEB,
        ActionType.READ_FILE,
        ActionType.CALCULATE,
        ActionType.EXPLAIN,
        ActionType.STUDY_PLAN,
        ActionType.SEND_NOTIFICATION,
        ActionType.SPEAK,
    }
    
    # Actions that NEVER require confirmation (safe)
    AUTO_CONFIRM = {
        ActionType.SPEAK,
        ActionType.SEND_NOTIFICATION,
    }
    
    def __init__(self):
        self._handlers: Dict[ActionType, Callable] = {}
        self._audit_log = []
    
    def register_handler(
        self, 
        action_type: ActionType, 
        handler: Callable[..., Awaitable[Dict[str, Any]]]
    ) -> None:
        """Register a handler for an action type."""
        if action_type in self.ALLOWED_ACTIONS:
            self._handlers[action_type] = handler
    
    async def execute(self, plan: ActionPlan) -> Dict[str, Any]:
        """
        Execute an approved action plan.
        
        Returns:
            {"success": bool, "result": Any, "error": str}
        """
        # Check if action is allowed
        if plan.action_type not in self.ALLOWED_ACTIONS:
            self._log_audit(plan, success=False, reason="Action not allowed")
            return {
                "success": False,
                "error": f"Action '{plan.action_type.value}' is not allowed",
            }
        
        # Check if handler exists
        if plan.action_type not in self._handlers:
            self._log_audit(plan, success=False, reason="No handler")
            return {
                "success": False,
                "error": f"No handler for '{plan.action_type.value}'",
            }
        
        # Execute
        try:
            handler = self._handlers[plan.action_type]
            result = await handler(**plan.parameters)
            self._log_audit(plan, success=True)
            return {
                "success": True,
                "result": result,
            }
        except Exception as e:
            self._log_audit(plan, success=False, reason=str(e))
            return {
                "success": False,
                "error": str(e),
            }
    
    def _log_audit(
        self, 
        plan: ActionPlan, 
        success: bool, 
        reason: str = ""
    ) -> None:
        """Log action execution for audit trail."""
        from datetime import datetime
        
        entry = {
            "timestamp": datetime.now().isoformat(),
            "action": plan.action_type.value,
            "parameters": plan.parameters,
            "success": success,
            "reason": reason,
        }
        self._audit_log.append(entry)
        
        # Keep only last 100 entries
        if len(self._audit_log) > 100:
            self._audit_log.pop(0)
    
    def get_audit_log(self) -> list:
        """Get recent audit log entries."""
        return self._audit_log.copy()


class IntegratedAssistant:
    """
    The main integrated assistant combining all layers.
    
    This is the top-level class that:
    1. Receives user input (text or voice)
    2. Routes through DialogueFlowController
    3. Uses Planner for action planning
    4. Uses Executor for action execution
    5. Returns responses (text and/or speech)
    
    USAGE:
    ```python
    assistant = IntegratedAssistant()
    
    # Register action handlers
    assistant.register_action(ActionType.OPEN_URL, open_url_handler)
    assistant.register_action(ActionType.SEARCH_WEB, search_web_handler)
    
    # Process user input
    response = await assistant.process("open youtube")
    print(response.text)  # "I'll open YouTube. Should I proceed?"
    
    response = await assistant.process("yes")
    print(response.text)  # "Done! Opened YouTube."
    ```
    """
    
    def __init__(self, llm_callback: Optional[Callable] = None):
        self.planner = Planner(llm_callback)
        self.executor = Executor()
        self.dialogue = DialogueFlowController(
            planner_callback=self._plan,
            executor_callback=self._execute,
        )
    
    def register_action(
        self, 
        action_type: ActionType, 
        handler: Callable[..., Awaitable[Dict[str, Any]]]
    ) -> None:
        """Register an action handler."""
        self.executor.register_handler(action_type, handler)
    
    async def process(self, user_input: str) -> DialogueResponse:
        """
        Process user input and return response.
        
        This is the main entry point.
        """
        return await self.dialogue.handle_input(user_input)
    
    async def _plan(
        self, 
        intent: IntentType, 
        entities: Dict[str, Any]
    ) -> Optional[ActionPlan]:
        """Internal: Create action plan."""
        context = self.dialogue.get_conversation_context()
        return await self.planner.plan(intent, entities, context)
    
    async def _execute(
        self, 
        action_type: str, 
        parameters: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Internal: Execute action."""
        try:
            at = ActionType(action_type)
        except ValueError:
            return {
                "success": False,
                "error": f"Unknown action type: {action_type}",
            }
        
        plan = ActionPlan(
            action_type=at,
            parameters=parameters,
            description="",
        )
        
        return await self.executor.execute(plan)
    
    def reset_conversation(self) -> str:
        """Reset conversation state. Returns new session ID."""
        return self.dialogue.reset()
    
    def get_audit_log(self) -> list:
        """Get executor audit log."""
        return self.executor.get_audit_log()
